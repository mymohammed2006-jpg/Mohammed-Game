# Pulls the number tables (song energy, beat grids, F8 equalizer) out of the original index.html into Data.cs
import re, sys, json
src = open(sys.argv[1], encoding='utf-8').read()
names = ['E1','E2','E3','E4','E5','E6','E7','E8','E9','E10','E11','EF1','EF2','EF3','EF4','EF5','EF6','EF7','EF8','BF1','BF3']
out = ['// generated by tools/extract_data.py from the original index.html: do not edit by hand', 'namespace MG;', '', 'public static partial class G', '{']
for n in names:
    m = re.search(r'[ ,]' + n + r'=\[([^\]]*)\]', src)
    vals = [v.strip() for v in m.group(1).split(',') if v.strip()]
    for v in vals: float(v)
    out.append(f'\tpublic static readonly double[] {n} = {{ {", ".join(vals)} }};')
m = re.search(r'[ ,]F8EQ="([^"]*)"', src)
out.append(f'\tpublic const string F8EQ = "{m.group(1)}";')
out.append('}')
open(sys.argv[2], 'w', encoding='utf-8').write('\n'.join(out) + '\n')
print('ok', len(names))
